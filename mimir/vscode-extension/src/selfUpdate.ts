/**
 * The shared site release, as this window sees it: where its tree is, the interpreter
 * it records, and the extension update it ships. The pure rules are in release.ts.
 */
import * as vscode from "vscode";
import * as fs from "fs";
import * as path from "path";
import { loadSiteConfig, compareVersions, releaseWriters, resolveReleaseRoot } from "./release";
import { showToast } from "./notifications";

/**
 * Root of this site's shared release tree, or "" on machines without one (the
 * `current` symlink is the presence probe), so every later resolution step falls through.
 */
export function releaseRoot(extensionRoot: string): string {
  const configured = vscode.workspace.getConfiguration("mimir").get<string>("releaseHome");
  // An explicit setting wins; otherwise a deployment may ship the path in the
  // extension's site.json (generated by the site's own build tooling, never committed
  // upstream). Empty and unset are the same: the declared default "" does not mask
  // site.json (see resolveReleaseRoot).
  const fromSite = loadSiteConfig(extensionRoot, (p) => fs.readFileSync(p, "utf8"))?.releaseHome;
  const root = resolveReleaseRoot(configured, fromSite);
  return root && fs.existsSync(path.join(root, "current")) ? root : "";
}

/**
 * The first of *files* (and the directories holding them) that anyone may rewrite, or
 * "". Each is followed to what it names, since `current` is a symlink.
 */
export function writableByAnyone(files: string[]): string {
  for (const file of files) {
    for (const p of [file, path.dirname(file)]) {
      try {
        const real = fs.realpathSync(p);
        if (releaseWriters(fs.statSync(real).mode) === "anyone") return real;
      } catch {
        // Missing: the caller's own existence check answers for it.
      }
    }
  }
  return "";
}

/** Interpreter recorded for the current shared release, or "" when there is none or
 *  when anyone could have rewritten it. */
export function sharedReleasePython(extensionRoot: string): string {
  const root = releaseRoot(extensionRoot);
  if (!root) return "";
  try {
    const record = path.join(root, "current", "PYTHON_COMMAND");
    const p = fs.readFileSync(record, "utf8").trim();
    if (!p || !fs.existsSync(p)) return "";
    const open = writableByAnyone([record, p]);
    if (open) {
      console.warn(`MIMIR: ignoring the release interpreter: ${open} is writable by anyone`);
      return "";
    }
    return p;
  } catch {
    return "";
  }
}

/**
 * Update this extension from the shared release when it ships a newer version.
 *
 * Once per window, off the startup path, a no-op without the release tree. Never
 * downgrades, so a rolled-back `current` is not fought; the user is offered a reload.
 */
export function maybeSelfUpdate(context: vscode.ExtensionContext): void {
  const root = releaseRoot(context.extensionUri.fsPath);
  if (!root) return;
  let marker: string;
  try {
    marker = fs.readFileSync(path.join(root, "current", "EXTENSION_VERSION"), "utf8").trim();
  } catch {
    return; // the marker is written by deploy/release.sh — no release mode here.
  }
  const installed = String(context.extension.packageJSON.version ?? "0.0.0");
  if (!marker || compareVersions(marker, installed) <= 0) return;
  const vsix = path.join(root, "current", "vsix", `mimir-${marker}.vsix`);
  const open = fs.existsSync(vsix) ? writableByAnyone([vsix]) : "";
  if (open) {
    void showToast(
      "error",
      `MIMIR ${marker} was not installed: ${open} is writable by any user of this machine, ` +
      "so anyone could have changed what it installs. Ask whoever runs the site release to fix its permissions."
    );
    return;
  }
  if (!fs.existsSync(vsix)) {
    void showToast(
      "info",
      `MIMIR ${marker} is available — install it manually (Extensions → Install from VSIX…):\n${vsix}`
    );
    return;
  }
  void vscode.window
    .withProgress(
      {
        location: vscode.ProgressLocation.Notification,
        title: `Updating the MIMIR extension to ${marker}…`,
      },
      () => vscode.commands.executeCommand("workbench.extensions.installExtension", vscode.Uri.file(vsix))
    )
    .then(
      () => {
        const reload = "Reload Window";
        void showToast("info", `MIMIR extension updated to ${marker}.`, reload)
          .then((choice) => {
            if (choice === reload) {
              void vscode.commands.executeCommand("workbench.action.reloadWindow");
            }
          });
      },
      (err: unknown) => console.warn("MIMIR: automatic extension update failed:", err)
    );
}
