/**
 * Root of this site's shared release tree, when one is present.
 *
 * Returns "" on machines without the tree (the `current` symlink is the
 * presence probe), so every following resolution step falls through unchanged
 * and the extension behaves exactly as before anywhere but the cluster.
 */
function releaseRoot(): string {
  const configured = vscode.workspace.getConfiguration("mimir").get<string>("releaseHome");
  // An explicit setting wins; otherwise a deployment may ship the path in the
  // extension's site.json (generated by the site's own build tooling — never
  // committed upstream, so nothing here is site-specific). Empty and unset are
  // the same thing — the declared default "" must not mask site.json (see
  // resolveReleaseRoot; until 1.1.2 it did, via ??).
  const fromSite = extensionRoot ? loadSiteConfig(extensionRoot, (p) => fs.readFileSync(p, "utf8"))?.releaseHome : undefined;
  const root = resolveReleaseRoot(configured, fromSite);
  return root && fs.existsSync(path.join(root, "current")) ? root : "";
}

/** Interpreter recorded for the current shared release, or "" when there is none. */
function sharedReleasePython(): string {
  const root = releaseRoot();
  if (!root) return "";
  try {
    const p = fs.readFileSync(path.join(root, "current", "PYTHON_COMMAND"), "utf8").trim();
    return p && fs.existsSync(p) ? p : "";
  } catch {
    return "";
  }
}

/**
 * Interpreter that runs the WS server: `bash -c` sources no profile, so `python3` from
 * PATH is rarely the right one. In order: `mimir.pythonPath`, `MIMIR_PYTHON`,
 * `<releaseHome>/current/PYTHON_COMMAND` (a shared site release), `<state home>/python`
 * (written by install.sh), then `python3` from PATH.
 */
function resolvePython(): string {
  const configured = vscode.workspace.getConfiguration("mimir").get<string>("pythonPath");
  if (configured) {
    return configured;
  }
  if (process.env.MIMIR_PYTHON) {
    return process.env.MIMIR_PYTHON;
  }
  const shared = sharedReleasePython();
  if (shared) {
    return shared;
  }
  const stateHome = process.env.MIMIR_STATE_HOME || path.join(os.homedir(), ".mimir");
  try {
    const interpreter = fs.readFileSync(path.join(stateHome, "python"), "utf8").trim();
    if (interpreter && fs.existsSync(interpreter)) {
      return interpreter;
    }
  } catch {
    // Not installed via install.sh, or the file was removed — fall through.
  }
  return "python3";
}

/**
 * Environment the MIMIR server process is spawned with: the extension host's, without
 * `PYTHONHOME` and `PYTHONPATH`, which would run the venv's python on the user's
 * packages. Only for the processes MIMIR starts; the user's shell is untouched.
 */
function mimirServerEnv(): NodeJS.ProcessEnv {
  const env = { ...process.env };
  delete env.PYTHONHOME;
  delete env.PYTHONPATH;
  return env;
}

/**
 * Update this extension from the shared release when it ships a newer version.
 *
 * Once per window, off the startup path, a no-op without the release tree. Never
 * downgrades, so a rolled-back `current` is not fought; the user is offered a reload.
 */
function maybeSelfUpdate(context: vscode.ExtensionContext): void {
  const root = releaseRoot();
  if (!root) return;
  let marker: string;
  try {
    marker = fs.readFileSync(path.join(root, "current", "EXTENSION_VERSION"), "utf8").trim();
  } catch {
    return; // the marker is written by deploy/release.sh — no release mode here.
  }
  const installed = String(context.extension.packageJSON.version ?? "0.0.0");
  if (!marker || compareVersions(marker, installed) <= 0) return;
  const vsix = path.join(root, "current", "vsix", `mimir-${marker}.vsix`);
  if (!fs.existsSync(vsix)) {
    void vscode.window.showInformationMessage(
      `MIMIR ${marker} is available — install it manually (Extensions → Install from VSIX…):\n${vsix}`
    );
    return;
  }
  void vscode.window
    .withProgress(
      {
        location: vscode.ProgressLocation.Notification,
        title: `Updating the MIMIR extension to ${marker}…`,
      },
      () => vscode.commands.executeCommand("workbench.extensions.installExtension", vscode.Uri.file(vsix))
    )
    .then(
      () => {
        const reload = "Reload Window";
        void vscode.window
          .showInformationMessage(`MIMIR extension updated to ${marker}.`, reload)
          .then((choice) => {
            if (choice === reload) {
              void vscode.commands.executeCommand("workbench.action.reloadWindow");
            }
          });
      },
      (err: unknown) => console.warn("MIMIR: automatic extension update failed:", err)
    );
}

/**
 * Append the host of *baseUrl* to the inherited no_proxy/NO_PROXY lists.
 *
 * On-prem vLLM hosts are reachable directly but an HTTP proxy will
 * black-hole them, which turns model resolution into an indefinite hang.
 */
function noProxyFor(baseUrl: string): Record<string, string> {
  let host: string;
  try {
    host = new URL(baseUrl).hostname;
  } catch {
    return {};
  }
  if (!host) {
    return {};
  }
  const merge = (v: string | undefined) => (v ? `${v},${host}` : host);
  return { no_proxy: merge(process.env.no_proxy), NO_PROXY: merge(process.env.NO_PROXY) };
}

// ── Virtual document provider for proposed file content (diff editor) ─────────

/** Stores proposed file content keyed by virtual URI path, for open_diff. */
const _diffProposedContent = new Map<string, string>();

/**
 * Reconstruct the "before" content by reverse-applying a unified diff patch.
 * Removes added lines (+) and restores removed lines (-) to recover the original.
 */
function _reversePatch(current: string, patch: string): string {
  const currentLines = current.split("\n");
  const result: string[] = [];
  const patchLines = patch.split("\n");

  let ci = 0; // index into currentLines

  for (let pi = 0; pi < patchLines.length; pi++) {
    const line = patchLines[pi];
    if (line.startsWith("---") || line.startsWith("+++") || line.startsWith("diff ")) continue;
    if (line.startsWith("@@")) {
      // @@ -oldStart,oldCount +newStart,newCount @@
      const m = line.match(/\+(\d+)(?:,(\d+))?/);
      if (m) {
        const newStart = parseInt(m[1], 10) - 1; // 0-based
        // Emit unchanged lines up to this hunk from current
        while (ci < newStart) {
          result.push(currentLines[ci++]);
        }
      }
      continue;
    }
    if (line.startsWith("+")) {
      // Line was added in the patch → skip it in the current (it exists there)
      ci++;
    } else if (line.startsWith("-")) {
      // Line was removed in the patch → restore it to the original
      result.push(line.slice(1));
    } else if (line.startsWith(" ")) {
      // Context line — present in both; advance current pointer
      result.push(currentLines[ci++]);
    }
  }
  // Emit any remaining lines after the last hunk
  while (ci < currentLines.length) {
    result.push(currentLines[ci++]);
  }
  return result.join("\n");
}

const _diffContentProvider = new class implements vscode.TextDocumentContentProvider {
  provideTextDocumentContent(uri: vscode.Uri): string {
    return _diffProposedContent.get(uri.path) ?? "";
  }
}();

// ── Plan preview: our own panel, rendered from the bytes on disk ─────────────
//
// VS Code's Markdown preview renders a cached document and can show a stale plan, so
// each show reads the file, renders it with the Markdown extension's engine
// (`markdown.api.render`) into a panel we own: one tab for every plan. Relative image
// paths become webview URIs; link clicks come back here to resolve.

/** The plan panel, while it is open. */
let _planPanel: vscode.WebviewPanel | undefined;

/** Absolute path of the plan the panel currently mirrors. */
let _currentPlanPath: string | undefined;

/** Bumped on every render, so a slow render cannot overwrite a newer one. */
let _planRenderSeq = 0;

function _escapeHtml(s: string): string {
  return s.replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]!));
}

/** The Markdown extension's folder, for its preview stylesheet. */
function _markdownMediaUri(): vscode.Uri | undefined {
  const ext = vscode.extensions.getExtension("vscode.markdown-language-features");
  return ext ? vscode.Uri.joinPath(ext.extensionUri, "media") : undefined;
}

/** True for `https:`, `data:`, `vscode-resource:`… and protocol-relative URLs. */
function _hasScheme(ref: string): boolean {
  return /^[a-z][\w+.-]*:/i.test(ref) || ref.startsWith("//");
}

/** `ref` from the plan, as an absolute path (fragment and query dropped). */
function _resolveFromPlan(ref: string, planAbs: string): string {
  let p = ref.replace(/[?#].*$/, "");
  try {
    p = decodeURI(p);
  } catch {
    /* keep it as written */
  }
  return path.isAbsolute(p) ? p : path.join(path.dirname(planAbs), p);
}

/**
 * Point every local `<img src>` at a webview URI. Returns the rewritten HTML and
 * the folders those images live in, which the panel must be allowed to read.
 */
function _rewriteImages(html: string, planAbs: string, webview: vscode.Webview): { html: string; dirs: string[] } {
  const dirs = new Set<string>();
  const out = html.replace(/(<img\b[^>]*?\bsrc=")([^"]*)(")/gi, (all, pre: string, src: string, post: string) => {
    if (!src || _hasScheme(src)) return all;
    const abs = _resolveFromPlan(src.replace(/&amp;/g, "&"), planAbs);
    dirs.add(path.dirname(abs));
    return pre + webview.asWebviewUri(vscode.Uri.file(abs)).toString() + post;
  });
  return { html: out, dirs: [...dirs] };
}

/** Follow a link clicked in the plan panel. In-page anchors never get here. */
function _openPlanLink(href: string): void {
  const planAbs = _currentPlanPath;
  if (_hasScheme(href) && !/^file:/i.test(href)) {
    void vscode.env.openExternal(vscode.Uri.parse(href));
    return;
  }
  if (!planAbs) return;
  const abs = /^file:/i.test(href) ? vscode.Uri.parse(href).fsPath : _resolveFromPlan(href, planAbs);
  if (!fs.existsSync(abs)) {
    void vscode.window.showWarningMessage(`MIMIR: ${abs} not found`);
    return;
  }
  if (fs.statSync(abs).isDirectory()) {
    void vscode.commands.executeCommand("revealInExplorer", vscode.Uri.file(abs));
    return;
  }
  vscode.workspace.openTextDocument(vscode.Uri.file(abs)).then(
    (doc) => vscode.window.showTextDocument(doc, { preview: true, viewColumn: vscode.ViewColumn.One }),
    () => vscode.commands.executeCommand("vscode.open", vscode.Uri.file(abs))
  );
}

/** Hands link clicks to the extension; scrolls in-page anchors itself. */
const _PLAN_SCRIPT = `
const vscode = acquireVsCodeApi();
document.addEventListener("click", (e) => {
  const a = e.target.closest && e.target.closest("a[href]");
  if (!a) return;
  const href = a.getAttribute("href");
  e.preventDefault();
  if (href.startsWith("#")) {
    const id = decodeURIComponent(href.slice(1));
    const el = document.getElementById(id) || document.getElementsByName(id)[0];
    if (el) el.scrollIntoView();
    return;
  }
  vscode.postMessage({ type: "open", href });
});`;

/** Read the current plan from disk and write it into the panel. */
async function _renderPlan(): Promise<void> {
  const panel = _planPanel;
  const abs = _currentPlanPath;
  if (!panel || !abs) return;
  const seq = ++_planRenderSeq;
  let body: string;
  try {
    const text = fs.readFileSync(abs, "utf8");
    try {
      body = await vscode.commands.executeCommand<string>("markdown.api.render", text);
    } catch {
      // Markdown extension disabled: the plan is still readable as text.
      body = `<pre>${_escapeHtml(text)}</pre>`;
    }
  } catch (e) {
    body = `<p>Cannot read ${_escapeHtml(abs)}</p><pre>${_escapeHtml(String(e))}</pre>`;
  }
  if (seq !== _planRenderSeq || panel !== _planPanel) return;
  const media = _markdownMediaUri();
  const images = _rewriteImages(body, abs, panel.webview);
  // Roots before html: the new page must be allowed to load what it references.
  panel.webview.options = {
    enableScripts: true,
    localResourceRoots: [
      ...(media ? [media] : []),
      vscode.Uri.file(path.dirname(abs)),
      ...images.dirs.map((d) => vscode.Uri.file(d)),
    ],
  };
  const sheets = media
    ? ["markdown.css", "highlight.css"]
        .map((f) => `<link rel="stylesheet" href="${panel.webview.asWebviewUri(vscode.Uri.joinPath(media, f))}">`)
        .join("\n")
    : "";
  const csp = panel.webview.cspSource;
  const nonce = Math.random().toString(36).slice(2) + Date.now().toString(36);
  panel.title = `Plan — ${path.basename(abs, path.extname(abs))}`;
  panel.webview.html = `<!DOCTYPE html>
<html><head><meta charset="utf-8">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src ${csp} 'unsafe-inline'; img-src ${csp} https: data:; script-src 'nonce-${nonce}';">
${sheets}
<style>body { padding: 0 26px; font-family: var(--vscode-markdown-font-family, var(--vscode-font-family)); font-size: var(--vscode-markdown-font-size, 14px); }</style>
</head><body class="vscode-body">${images.html}
<script nonce="${nonce}">${_PLAN_SCRIPT}</script></body></html>`;
}

/** Poller for the plan the panel shows, if any. */
let _previewWatch: { path: string; mtimeMs: number; size: number; timer: NodeJS.Timeout } | undefined;

function _stopPreviewWatch(): void {
  if (_previewWatch) {
    clearInterval(_previewWatch.timer);
    _previewWatch = undefined;
  }
}

/** Poll `abs` and re-render the panel whenever the file changes on disk. */
function _watchPreviewedFile(abs: string): void {
  const stamp = (): { mtimeMs: number; size: number } => {
    try {
      const st = fs.statSync(abs);
      return { mtimeMs: st.mtimeMs, size: st.size };
    } catch {
      return { mtimeMs: 0, size: -1 };
    }
  };
  _stopPreviewWatch();
  const timer = setInterval(() => {
    if (!_previewWatch) return;
    const now = stamp();
    if (now.mtimeMs !== _previewWatch.mtimeMs || now.size !== _previewWatch.size) {
      Object.assign(_previewWatch, now);
      void _renderPlan();
    }
  }, 1000);
  _previewWatch = { path: abs, ...stamp(), timer };
}

/** Show `abs` in the plan panel, opening the panel if needed. */
function _showPlanPreview(abs: string): void {
  _currentPlanPath = abs;
  if (!_planPanel) {
    const media = _markdownMediaUri();
    _planPanel = vscode.window.createWebviewPanel(
      "mimir.plan",
      "Plan",
      // Active, not Beside: the chat lives in the side bar, so "beside" meant beside
      // the editor group — splitting the editor area in two and leaving the plan half
      // a window wide. The plan is a document to read, so it opens as a tab in the
      // group already there and fills it. Focus comes with it, or the tab would open
      // behind the file the user was reading and look like nothing had happened.
      { viewColumn: vscode.ViewColumn.Active, preserveFocus: false },
      { enableScripts: true, localResourceRoots: media ? [media] : [] }
    );
    _planPanel.webview.onDidReceiveMessage((m) => {
      if (m?.type === "open" && typeof m.href === "string") _openPlanLink(m.href);
    });
    _planPanel.onDidDispose(() => {
      _planPanel = undefined;
      _stopPreviewWatch();
    });
  } else {
    // Same reasoning: an existing panel is brought to the front of its group rather
    // than left behind whatever tab is on top of it.
    _planPanel.reveal(undefined, false);
  }
  // Re-baseline the poller before the read, so a write landing in between is
  // caught on the next tick rather than lost.
  _watchPreviewedFile(abs);
  void _renderPlan();
}

export function activate(context: vscode.ExtensionContext): void {
  extensionRoot = context.extensionUri.fsPath;
  context.subscriptions.push(
    vscode.workspace.registerTextDocumentContentProvider("mimir-diff", _diffContentProvider)
  );

  const provider = new MimirAgentViewProvider(context.extensionUri, context.globalState);
  context.subscriptions.push(
    vscode.window.registerWebviewViewProvider("mimir.chatView", provider, {
      webviewOptions: { retainContextWhenHidden: true },
    })
  );

  // `onStartupFinished` activates us with the chat panel possibly still closed,
  // so the remembered endpoint is probed here rather than on the first view
  // resolve: MIMIR is already connected by the time the user opens the panel.
  void provider.maybeAutoConnect();

  // Shared-release mode: offer to pick up the current release's extension when
  // it is newer than the one installed. No-op where the release tree is absent.
  maybeSelfUpdate(context);

  // Active-editor context: tell the webview which file (and selected line range)
  // is focused, so the user can attach it to a message with one click (opt-in chip).
  // Selection changes are debounced to avoid a flood while dragging.
  let selectionTimer: ReturnType<typeof setTimeout> | undefined;
  const pushEditor = () => provider.pushActiveEditor();
  context.subscriptions.push(
    vscode.window.onDidChangeActiveTextEditor(pushEditor),
    vscode.window.onDidChangeTextEditorSelection(() => {
      if (selectionTimer) clearTimeout(selectionTimer);
      selectionTimer = setTimeout(pushEditor, 120);
    })
  );

  context.subscriptions.push(
    vscode.commands.registerCommand("mimir.openChat", () =>
      vscode.commands.executeCommand("mimir.chatView.focus")
    )
  );

  context.subscriptions.push(
    vscode.commands.registerCommand("mimir.startServer", () =>
      startServer(context)
    )
  );

  context.subscriptions.push(
    vscode.commands.registerCommand("mimir.stopServer", () => stopServer())
  );
}

/**
 * End the server this window is responsible for: a child it spawned, or the pid of one
 * it attached to. SIGTERM, so the server's own handler reaps the MCP servers. A
 * detached server is exempt: it was kept going on purpose.
 */
function endServerUnlessKeptRunning(): void {
  if (!serverDetached) {
    if (serverProcess && !serverProcess.killed) {
      serverProcess.kill();
    } else if (attachedPid !== undefined) {
      try {
        process.kill(attachedPid, "SIGTERM");
      } catch {
        // Already gone, or not ours to signal. Either way there is nothing to end,
        // and a window closing must not fail over it.
      }
    }
  }
  serverProcess = undefined;
  attachedPid = undefined;
}

export function deactivate(): void {
  _stopPreviewWatch();
  // The server is deliberately left running when detached; an interval in a disposed
  // extension host is the one part of that which must not survive.
  _stopLogTail?.dispose();
  endServerUnlessKeptRunning();
}

