"""The execution context as its readers get it: every record behind a read-only view.

A function that only reads takes a :class:`ContextView`; ``ExecutionContext`` satisfies it
as it is, so nothing is copied, and the type checker refuses a write through it — an
assignment, or a mutating call on a set, a mapping or a list. Each view restates its
record's fields with the read-only type (``test_architecture`` holds them to it).
"""
from __future__ import annotations

from typing import AbstractSet, Any, Mapping, Protocol, Sequence



class LoopControlView(Protocol):
    @property
    def write_calls(self) -> AbstractSet[tuple[Any, ...]]: ...
    @property
    def call_fails(self) -> Mapping[tuple[Any, ...], int]: ...
    @property
    def repeat_warned(self) -> AbstractSet[Any]: ...
    @property
    def call_results(self) -> Mapping[tuple[Any, ...], tuple[str, int]]: ...
    @property
    def repeat_noted(self) -> AbstractSet[Any]: ...


class EditFailuresView(Protocol):
    @property
    def signature(self) -> Any: ...
    @property
    def identical(self) -> int: ...
    @property
    def streak(self) -> int: ...


class DiscoveryView(Protocol):
    @property
    def searched(self) -> bool: ...
    @property
    def inspected_dirs(self) -> AbstractSet[str]: ...
    @property
    def checked_paths(self) -> AbstractSet[str]: ...
    @property
    def read_files(self) -> AbstractSet[str]: ...
    @property
    def existing_paths(self) -> AbstractSet[str]: ...
    @property
    def delegated_read_files(self) -> AbstractSet[str]: ...
    @property
    def similar_candidates_by_dir(self) -> Mapping[str, AbstractSet[str]]: ...
    @property
    def search_tool_calls(self) -> int: ...


class EditsView(Protocol):
    @property
    def planned_edit_targets(self) -> AbstractSet[str]: ...
    @property
    def declared_edit_set(self) -> AbstractSet[str]: ...
    @property
    def dirty_written_files(self) -> AbstractSet[str]: ...
    @property
    def code_mutation_started(self) -> bool: ...
    @property
    def cross_file_grep_old_text(self) -> str | None: ...
    @property
    def cross_file_grep_source(self) -> str | None: ...
    @property
    def last_replace_old_text(self) -> str | None: ...
    @property
    def last_replace_new_text(self) -> str: ...
    @property
    def last_replace_file(self) -> str: ...
    @property
    def edit_failures(self) -> Mapping[str, EditFailuresView]: ...
    @property
    def steps_since_last_edit(self) -> int: ...
    @property
    def last_edit_success_path(self) -> str: ...


class ChecksView(Protocol):
    @property
    def validated_files(self) -> AbstractSet[str]: ...
    @property
    def validation_tier_by_file(self) -> Mapping[str, str]: ...
    @property
    def validation_fail_count_by_file(self) -> Mapping[str, int]: ...
    @property
    def unverifiable_files(self) -> AbstractSet[str]: ...
    @property
    def builtin_check_stamp(self) -> Mapping[str, tuple[int, int]]: ...
    @property
    def builtin_check_findings(self) -> Mapping[str, str]: ...


class ExecutionView(Protocol):
    @property
    def runs(self) -> Mapping[str, Mapping[str, Any]]: ...
    @property
    def tests_run(self) -> AbstractSet[str]: ...
    @property
    def test_failure_signatures(self) -> Mapping[str, Sequence[str]]: ...
    @property
    def exercise_advice_closed(self) -> bool: ...
    @property
    def exercise_blocked_reason(self) -> str: ...
    @property
    def unwatched_runs(self) -> AbstractSet[str]: ...


class EnvironmentView(Protocol):
    @property
    def unresolved_modules(self) -> AbstractSet[str]: ...
    @property
    def env_probed(self) -> bool: ...
    @property
    def env_mutations(self) -> Sequence[Mapping[str, Any]]: ...


class DenialsView(Protocol):
    @property
    def denied_tool_calls(self) -> Sequence[Mapping[str, Any]]: ...
    @property
    def denial_history(self) -> Sequence[Mapping[str, Any]]: ...
    @property
    def handback_told(self) -> bool: ...


class PlanStateView(Protocol):
    @property
    def todo_written(self) -> bool: ...
    @property
    def plan_written(self) -> bool: ...
    @property
    def todo_file_path(self) -> str: ...
    @property
    def checklist_stamp(self) -> int | None: ...
    @property
    def last_todo_tick_path(self) -> str: ...


class NudgeStateView(Protocol):
    @property
    def nudge_counts(self) -> Mapping[str, int]: ...
    @property
    def transient_reminders(self) -> Sequence[Any]: ...
    @property
    def last_call_reminders(self) -> Sequence[Any]: ...
    @property
    def repeat_alert(self) -> tuple[Any, ...] | None: ...
    @property
    def moving_test_alert(self) -> str | None: ...
    @property
    def moving_test_told(self) -> Sequence[Any]: ...
    @property
    def consecutive_noop_turns(self) -> int: ...
    @property
    def evidence_handback_used(self) -> bool: ...


class BookkeepingView(Protocol):
    @property
    def tool_msg_files(self) -> Mapping[str, Sequence[str]]: ...
    @property
    def pinned_call_ids(self) -> AbstractSet[str]: ...
    @property
    def skills_loaded(self) -> Mapping[str, str]: ...
    @property
    def skill_suffix(self) -> str: ...
    @property
    def observed_agent_mode(self) -> str | None: ...
    @property
    def workspace_root(self) -> str: ...
    @property
    def session_id(self) -> str: ...
    @property
    def loop_control(self) -> LoopControlView: ...


class ContextView(Protocol):
    @property
    def discovery(self) -> DiscoveryView: ...
    @property
    def edits(self) -> EditsView: ...
    @property
    def checks(self) -> ChecksView: ...
    @property
    def execution(self) -> ExecutionView: ...
    @property
    def env(self) -> EnvironmentView: ...
    @property
    def denials(self) -> DenialsView: ...
    @property
    def plan(self) -> PlanStateView: ...
    @property
    def nudges(self) -> NudgeStateView: ...
    @property
    def bookkeeping(self) -> BookkeepingView: ...
    @property
    def workflow_state(self) -> str: ...
    @property
    def action_op_count(self) -> int: ...
    def get(self, name: str) -> Any: ...
